const assert=require('node:assert/strict');
const aggregate=require('./resolution-comparison/compute.js');
const consensus=require('./threshold-consensus/compute.js');
const rank=require('./weighted-ranking/compute.js');
assert.deepEqual(aggregate([[1,3],[5,7]],1,1),[[4]]);
assert.deepEqual(aggregate([[1,3],[5,7]],2,2),[[1,3],[5,7]]);
assert.deepEqual(aggregate([[1,3,5],[7,9,11]],1,2),[[4,7]]);
assert.throws(()=>aggregate([[1],[2,3]],1,1));assert.throws(()=>aggregate([[1]],2,1));assert.throws(()=>aggregate([[NaN]],1,1));
const series=[{id:'a',values:[.5,.8,.1]},{id:'b',values:[.5,.2,.9]},{id:'c',values:[.1,.9,.8]}];
assert.deepEqual(consensus(series,['a','b','c'],.5,'majority'),{votes:[2,2,2],required:2,pass:[true,true,true]});
assert.deepEqual(consensus(series,['a','b'],.5,'majority').pass,[true,false,false]);
assert.deepEqual(consensus(series,['a','b','c'],.5,'all').pass,[false,false,false]);
assert.deepEqual(consensus(series,['a'],.5,'any').pass,[true,true,false]);
assert.deepEqual(consensus(series,[],0,'all'),{votes:[0,0,0],required:null,pass:[false,false,false]});
assert.throws(()=>consensus(series,['missing'],.5,'any'));assert.throws(()=>consensus(series,['a','a'],.5,'any'));
assert.throws(()=>consensus([{id:'a',values:[NaN]}],['a'],.5,'any'));
const items=[{id:'a',scores:[9,4,6]},{id:'b',scores:[5,9,5]},{id:'c',scores:[6,6,9]}];
assert.equal(rank(items,[1,1,1],10).rows[0].id,'c');assert.equal(rank(items,[1,0,0],10).rows[0].id,'a');assert.equal(rank(items,[0,1,0],10).rows[0].id,'b');
assert.ok(rank(items,[0,0,0],10).rows.every(row=>row.total===null));
const weighted=rank(items,[2,3,5],10);assert.ok(Math.abs(weighted.normalized.reduce((a,b)=>a+b)-1)<1e-12);
for(const row of weighted.rows)assert.ok(Math.abs(row.contributions.reduce((a,b)=>a+b)-row.total)<1e-12);
const equal=rank([{id:'a',scores:[3,3]},{id:'b',scores:[3,3]}],[4,6],10).rows;assert.equal(equal[0].total,equal[1].total);
for(const weights of [[0,1],[1,0],[3,7]])assert.equal(rank([{id:'a',scores:[4,5]},{id:'b',scores:[3,4]}],weights,10).rows[0].id,'a');
assert.throws(()=>rank(items,[-1,1,1],10));assert.throws(()=>rank(items,[1],10));assert.throws(()=>rank(items,[1,1,1],5));
