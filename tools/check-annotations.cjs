// node tools/check-annotations.cjs；可設 PLAYWRIGHT_CHANNEL=chrome 使用本機 Chrome。
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, channel: process.env.PLAYWRIGHT_CHANNEL || undefined });
  try {
    const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, hasTouch: true });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const url = process.env.AGENTDECK_TEST_URL || pathToFileURL(path.resolve(__dirname, '../templates/blank/index.html')).href;
    await page.goto(url);
    await page.evaluate(() => storyReader.go(1));
    const openTools = async () => {
      if (!await page.locator('#reader-tools-menu').evaluate(el => el.open)) await page.getByLabel('標示工具', { exact: true }).click();
    };
    assert.equal(await page.locator('#reader-drawing').isVisible(), false);
    const playBox = await page.locator('#zoom').boundingBox();
    const toolsBox = await page.getByLabel('標示工具', { exact: true }).boundingBox();
    assert.ok(Math.abs(playBox.y - toolsBox.y) < 2 && toolsBox.x > playBox.x);
    await openTools();
    assert.equal(await page.evaluate(() => storyReader.index), 1);
    await page.getByLabel('標示工具', { exact: true }).click();
    assert.equal(await page.locator('#reader-drawing').isVisible(), false);
    const mode = async name => { await openTools(); await page.locator(`#reader-drawing [data-mode=${name}]`).click(); };
    const count = () => page.locator('#reader-ink polyline').count();
    const settle = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    async function draw() {
      await settle();
      const r = await page.locator('#page h1').boundingBox();
      await page.mouse.move(r.x + 15, r.y + 15);
      await page.mouse.down();
      await page.mouse.move(r.x + 100, r.y + 30, { steps: 8 });
      await page.mouse.up();
    }
    await mode('pen');
    await draw();
    assert.equal(await count(), 1);
    const original = await page.locator('#reader-ink').innerHTML();
    await page.keyboard.press('Escape');
    await settle();
    assert.equal(await page.locator('[data-mode=normal]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('#reader-ink').innerHTML(), original);
    await page.locator('#next').click();
    assert.equal(await count(), 0);
    await page.locator('#prev').click();
    assert.equal(await page.locator('#reader-ink').innerHTML(), original);
    await mode('pen');
    await openTools();
    await page.getByLabel('畫筆選項', { exact: true }).click();
    await page.getByLabel('畫筆顏色').selectOption('#2563eb');
    await page.getByLabel('畫筆粗細').selectOption('10');
    await openTools();
    await page.getByLabel('畫筆選項', { exact: true }).click();
    await draw();
    assert.equal(await count(), 2);
    assert.equal(await page.locator('#reader-ink polyline').last().getAttribute('stroke'), '#2563eb');
    assert.equal(await page.locator('#reader-ink polyline').last().getAttribute('stroke-width'), '10');
    await page.getByRole('button', { name: '復原上一筆', exact: true }).click();
    assert.equal(await page.locator('#reader-ink').innerHTML(), original);
    // 純等比例縮放與捲動保留筆跡，覆蓋層隨內容區移動。
    await page.locator('#page').evaluate(el => { el.style.zoom = '1.1'; });
    await settle();
    assert.equal(await count(), 1);
    await page.evaluate(() => window.scrollTo(0, 80));
    await settle();
    const boxes = await page.evaluate(() => ['page', 'reader-ink'].map(id => {
      const r = document.getElementById(id).getBoundingClientRect();
      return [r.x, r.y, r.width, r.height];
    }));
    boxes[0].forEach((value, i) => assert.ok(Math.abs(value - boxes[1][i]) < 1));
    await page.locator('#page').evaluate(el => { el.style.zoom = ''; });
    await page.evaluate(() => window.scrollTo(0, 0));
    await settle();
    // 設定對話框期間不畫筆、不翻頁。
    await page.getByRole('button', { name: '設定', exact: true }).click();
    await page.keyboard.press('d');
    assert.equal(await page.evaluate(() => storyReader.index), 1);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('[data-mode=pen]').getAttribute('aria-pressed'), 'true');
    await page.locator('#edit-toggle').click();
    assert.equal(await page.locator('[data-mode=normal]').getAttribute('aria-pressed'), 'true');
    assert.equal(await page.locator('[data-mode=pen]').isDisabled(), true);
    await page.locator('#edit-toggle').click();
    assert.equal(await page.locator('[data-mode=pen]').isDisabled(), false);
    // 雷射筆只有單一光點，移動時不產生尾跡，且不攔截頁面按鈕。
    await page.locator('#page .stage').evaluate(el => {
      const button = document.createElement('button');
      button.id = 'annotation-probe'; button.textContent = '互動測試';
      button.onclick = () => { button.dataset.clicked = 'yes'; };
      el.append(button);
    });
    await mode('laser');
    await page.locator('#annotation-probe').hover();
    assert.equal(await page.locator('#reader-laser b').count(), 1);
    await page.locator('#annotation-probe').click();
    assert.equal(await page.locator('#annotation-probe').getAttribute('data-clicked'), 'yes');
    const probe = await page.locator('#annotation-probe').boundingBox();
    await page.mouse.move(probe.x + 20, probe.y + 10, { steps: 12 });
    assert.equal(await page.locator('#reader-laser').evaluate(el => el.childElementCount), 1);
    assert.equal(await page.locator('#reader-laser i').count(), 0);
    assert.equal(await page.locator('#reader-laser b').count(), 1);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#reader-laser').evaluate(el => el.childElementCount), 0);
    await mode('pen');
    await draw();
    assert.ok(await count() > 0);
    await page.setViewportSize({ width: 900, height: 800 });
    await page.waitForFunction(() => !document.querySelector('#reader-ink polyline'));
    assert.match(await page.locator('#reader-drawing [role=status]').textContent(), /重新排列/);
    // 觸控拖曳、pointercancel、單點及清除。
    await settle();
    const r = await page.locator('#page h1').boundingBox();
    const cdp = await context.newCDPSession(page);
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: r.x + 20, y: r.y + 15 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: r.x + 90, y: r.y + 25 }] });
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
    assert.equal(await count(), 1);
    await page.touchscreen.tap(r.x + 50, r.y + 15);
    assert.equal(await count(), 2);
    await page.getByRole('button', { name: '清除本頁', exact: true }).click();
    assert.equal(await count(), 0);
    assert.equal(await page.getByRole('button', { name: '復原上一筆', exact: true }).isDisabled(), true);
    await draw();
    await page.reload();
    await page.evaluate(() => storyReader.go(1));
    assert.equal(await count(), 0);
    await page.setViewportSize({ width: 1280, height: 900 });
    await settle();
    // 文字框輸入不觸發翻頁／編輯快捷鍵，內容安全插入並逐頁保留。
    await mode('text');
    const title = await page.locator('#page h1').boundingBox();
    await page.mouse.click(title.x + 20, title.y + 15);
    await page.getByLabel('文字框內容').fill('課堂重點 <b>不是 HTML</b>\n第二行');
    await page.keyboard.type('ad');
    assert.equal(await page.evaluate(() => storyReader.index), 1);
    await page.locator('#reader-text-dialog button[value=save]').click();
    await settle();
    assert.equal(await page.locator('.reader-text-box').count(), 1);
    assert.equal(await page.locator('.reader-text-box b').count(), 0);
    assert.match(await page.locator('.reader-text-box').textContent(), /第二行ad/);
    await page.locator('#next').click();
    assert.equal(await page.locator('.reader-text-box').count(), 0);
    await page.locator('#prev').click();
    assert.equal(await page.locator('.reader-text-box').count(), 1);
    await page.locator('.reader-text-box').dblclick();
    await page.getByLabel('文字框內容').fill('修改後的文字');
    await page.locator('#reader-text-dialog button[value=save]').click();
    await settle();
    assert.equal(await page.locator('.reader-text-box').textContent(), '修改後的文字');
    await page.locator('.reader-text-box').dblclick();
    await page.getByLabel('文字框內容').fill('取消這次修改');
    await page.keyboard.press('Escape');
    await settle();
    assert.equal(await page.locator('.reader-text-box').textContent(), '修改後的文字');
    // 選取工具、整框樣式、拖曳與角落調整寬度；縮放後以內容座標移動。
    await page.locator('.reader-text-box').click();
    assert.equal(await page.locator('#reader-text-tools').isVisible(), true);
    await page.getByLabel('文字框字級', { exact: true }).fill('32');
    await page.getByLabel('文字框字級', { exact: true }).press('Tab');
    await page.getByLabel('文字框顏色', { exact: true }).selectOption('#2563eb');
    await page.getByLabel('文字框粗體', { exact: true }).click();
    assert.equal(await page.locator('.reader-text-box>div').evaluate(el => el.style.fontSize), '32px');
    assert.equal(await page.locator('.reader-text-box>div').evaluate(el => el.style.fontWeight), '700');
    assert.equal(await page.locator('.reader-text-box').getAttribute('data-color'), '#2563eb');
    await page.locator('#page').evaluate(el => { el.style.zoom = '1.1'; });
    await settle();
    const boxBefore = await page.locator('.reader-text-box').boundingBox();
    const xBefore = Number(await page.locator('.reader-text-box').getAttribute('x'));
    await page.mouse.move(boxBefore.x + 30, boxBefore.y + 20);
    await page.mouse.down();
    await page.mouse.move(boxBefore.x + 85, boxBefore.y + 53, { steps: 8 });
    await page.mouse.up();
    assert.ok(Math.abs(Number(await page.locator('.reader-text-box').getAttribute('x')) - xBefore - 50) < 2);
    const beforeWidth = Number(await page.locator('.reader-text-box').getAttribute('width'));
    const handle = await page.getByLabel('調整文字框寬度').boundingBox();
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2);
    await page.mouse.down();
    await page.mouse.move(handle.x + handle.width / 2 + 55, handle.y + handle.height / 2, { steps: 8 });
    await page.mouse.up();
    assert.ok(Math.abs(Number(await page.locator('.reader-text-box').getAttribute('width')) - beforeWidth - 50) < 2);
    await page.locator('#next').click();
    assert.equal(await page.locator('#reader-text-tools').isVisible(), false);
    await page.locator('#prev').click();
    assert.equal(await page.locator('.reader-text-box>div').evaluate(el => el.style.fontSize), '32px');
    await page.locator('.reader-text-box').click();
    await page.keyboard.press('Delete');
    assert.equal(await page.locator('.reader-text-box').count(), 0);
    assert.equal(await page.locator('#reader-text-tools').isVisible(), false);
    await page.locator('#page').evaluate(el => { el.style.zoom = ''; });
    await settle();
    // 真正的全螢幕放大中仍可書寫，退出時不留下雷射或失效的 capture。
    await page.locator('#zoom').click();
    await settle();
    assert.equal(await page.evaluate(() => !!document.fullscreenElement), true);
    await mode('pen');
    await draw();
    assert.equal(await count(), 1);
    await page.locator('#zoom').click();
    await settle();
    assert.equal(await page.evaluate(() => !!document.fullscreenElement), false);
    // 窄螢幕工具不溢出，且工具標籤／空白不會翻頁。
    await page.setViewportSize({ width: 390, height: 844 });
    await settle();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await openTools();
    await page.getByLabel('畫筆選項', { exact: true }).click();
    await page.locator('#reader-drawing label').first().click();
    assert.equal(await page.evaluate(() => storyReader.index), 1);
    // 獨立閱讀器不依賴編輯層。
    await context.route('**/deck-editor.js', route => route.fulfill({ body: '', contentType: 'application/javascript' }));
    await page.reload();
    await page.evaluate(() => storyReader.go(1));
    await mode('pen');
    await draw();
    assert.equal(await count(), 1);
    assert.deepEqual(errors, []);
    console.log('PASS: 離線畫筆、文字框新增修改取消、無拖尾雷射穿透、逐頁暫存、復原清除、縮放捲動、重排提示、編輯互斥、觸控取消與獨立閱讀器');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
